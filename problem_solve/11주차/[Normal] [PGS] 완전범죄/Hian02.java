/*
문제 정의

여러 개의 물건이 있고, 각 물건은 A도둑 또는 B도둑 중 반드시 한 명이 훔쳐야 합니다.

물건 i를 훔칠 때 발생하는 흔적은 다음과 같습니다.
info[i][0] : A도둑이 훔쳤을 때 A의 흔적
info[i][1] : B도둑이 훔쳤을 때 B의 흔적

경찰에 붙잡히지 않으려면
A의 흔적 < n
B의 흔적 < m
모두 만족해야 합니다.

모든 물건을 훔친 뒤, 위 조건을 만족하는 경우 중에서 A의 흔적이 가장 작은 값을 구해야 합니다.
가능한 방법이 없다면 -1을 반환합니다.
*/

/*
접근 방법

DP를 사용합니다.
dp[a] = 지금까지 확인한 물건들을 모두 훔쳤을 때, A의 흔적이 정확히 a개인 경우, B가 남길 수 있는 최소 흔적
예를 들어 dp[3] = 5라면 A의 흔적을 정확히 3개 남기면서 지금까지의 물건을 모두 훔치는 방법 중 B의 최소 흔적은 5개라는 뜻입니다.

A의 흔적이 같은 경우에는 B의 흔적이 가장 작은 경우만 남기면 됩니다.
이후 어떤 물건을 훔치더라도 B의 흔적이 작은 상태가 항상 유리하기 때문입니다.

초기 상태
아직 물건을 하나도 훔치지 않았으므로
A의 흔적 = 0, B의 흔적 = 0
따라서 dp[0] = 0
나머지 상태는 아직 만들 수 없으므로 INF로 초기화합니다.

각 물건을 처리할 때는 두 가지 경우를 확인합니다.

1. A도둑이 훔치는 경우
A의 흔적이 info[i][0]만큼 증가합니다.
next[a + info[i][0]]를 갱신합니다.
단, a + info[i][0] < n이어야 합니다.

2. B도둑이 훔치는 경우
B의 흔적이 info[i][1]만큼 증가합니다.
next[a]를 갱신합니다.
단, dp[a] + info[i][1] < m이어야 합니다.


각 물건은 반드시 한 명이 훔쳐야 하므로 현재 물건을 처리하기 전 dp와 처리한 후 next를 별도로 관리합니다.
이렇게 하면 하나의 물건을 여러 번 훔치는 문제를 방지할 수 있습니다.
모든 물건을 처리한 뒤에는 dp[0], dp[1], ..., dp[n - 1] 순서로 확인합니다.
처음으로 INF가 아닌 위치 a가 A의 최소 흔적이므로 정답입니다.
*/

/*
문제 풀이
*/

import java.util.Arrays;

class Solution {
    public int solution(int[][] info, int n, int m) {
        /*
        도달할 수 없는 상태를 나타내는 값입니다.
        실제 흔적의 최댓값보다 충분히 큰 값으로 설정합니다.
        */
        final int INF = 1_000_000_000;
        /*
        dp[a]
        A의 흔적이 정확히 a개일 때 B가 남길 수 있는 최소 흔적입니다.
        A의 흔적은 n 이상이 되면 안 되므로 배열의 크기는 n입니다.
        */
        int[] dp = new int[n];
        /*
        처음에는 가능한 상태가 없다고 가정합니다.
        */
        Arrays.fill(dp, INF);
        /*
        물건을 훔치기 전에는 A의 흔적 = 0, B의 흔적 = 0
        */
        dp[0] = 0;
        /*
        모든 물건을 하나씩 처리합니다.
        */
        for (int i = 0; i < info.length; i++) {
            int traceA = info[i][0];
            int traceB = info[i][1];
            /*
            현재 물건을 훔친 이후의 새로운 DP 상태를 저장합니다.
            이전 물건까지의 결과와 현재 물건을 처리한 결과를 구분하기 위해 새로운 배열을 사용합니다.
            */
            int[] next = new int[n];
            Arrays.fill(next, INF);
            /*
            지금까지 만들 수 있는 모든 A 흔적 상태를 확인합니다.
            */
            for (int a = 0; a < n; a++) {
                /*
                현재 상태에 도달할 수 없다면 더 이상 확인할 필요가 없습니다.
                */
                if (dp[a] == INF) {
                    continue;
                }
                /*
                1. 현재 물건을 A도둑이 훔치는 경우
                A의 흔적이 traceA만큼 증가합니다.
                B의 흔적은 변하지 않습니다.
                */
                int nextA = a + traceA;
                /*
                A의 흔적이 n 이상이 되면 경찰에 붙잡히므로 제외합니다.
                */
                if (nextA < n) {
                    next[nextA] = Math.min(next[nextA],dp[a]);
                }
                /*
                2. 현재 물건을 B도둑이 훔치는 경우
                A의 흔적은 변하지 않습니다.
                B의 흔적이 traceB만큼 증가합니다.
                */
                int nextB = dp[a] + traceB;
                /*
                B의 흔적이 m 이상이 되면 경찰에 붙잡히므로 제외합니다.
                */
                if (nextB < m) {
                    next[a] = Math.min(next[a],nextB);
                }
            }
            /*
            현재 물건까지 모두 훔친 결과를 다음 물건을 위한 DP로 사용합니다.
            */
            dp = next;
        }

        /*
        모든 물건을 처리했습니다.
        A의 흔적이 작은 값부터 확인하면 처음 발견한 가능한 상태가 정답입니다.
        */
        for (int a = 0; a < n; a++) {
            if (dp[a] != INF) {
                return a;
            }
        }
        /*
        두 도둑 모두 경찰에 붙잡히지 않으면서 모든 물건을 훔치는 방법이 없는 경우입니다.
        */
        return -1;
    }
}


/*
시간복잡도

물건의 개수를 L이라고 하겠습니다.
각 물건에 대해 A의 가능한 흔적 0 ~ n-1을 확인합니다.
각 상태에서는 A가 훔치는 경우, B가 훔치는 경우 두 가지만 계산합니다.
따라서 시간복잡도는 O(L * n)
*/
