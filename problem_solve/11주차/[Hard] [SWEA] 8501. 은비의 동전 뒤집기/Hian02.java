/*
문제 정의

1부터 N까지 서로 다른 숫자가 적힌 동전 N개가 모두 뒷면을 보이며 일렬로 나열되어 있습니다.
은비는 왼쪽부터 오른쪽으로 동전을 확인합니다.

현재 동전의 숫자가 x라면, 오른쪽에 있는 동전 중 x보다 큰 숫자의 동전들을 모두 뒤집습니다.
모든 동전을 확인한 뒤 앞면을 보이는 동전의 개수를 계산합니다.

N개 동전의 배치는 총 N!가지입니다.
문제에서 구해야 하는 값은 모든 N!가지 배치에서 최종적으로 앞면을 보이는 동전 개수의 총합입니다.

정답이 매우 커질 수 있으므로 1,000,000,007로 나눈 나머지를 출력해야 합니다.
*/

/*
접근 방법

DP를 사용합니다.

1. 동전이 뒤집히는 조건 분석

숫자가 x인 동전을 생각해 보겠습니다.

x보다 작은 숫자의 동전이 왼쪽에 있다면, 은비가 그 동전을 확인할 때 x번 동전을 뒤집습니다.
반대로 x보다 큰 숫자의 동전은 x번 동전을 뒤집을 수 없습니다.

따라서 x번 동전이 뒤집히는 횟수는 자신보다 왼쪽에 있는 자신보다 작은 숫자의 동전 개수와 같습니다.

모든 동전은 처음에 뒷면이므로
뒤집힌 횟수가 짝수 -> 뒷면
뒤집힌 횟수가 홀수 -> 앞면
이 됩니다.


2. N-1개에서 N개로 확장하기

1부터 N-1까지의 동전 배치가 있다고 가정합니다.
이 배치에 가장 큰 숫자인 N을 추가합니다.

예를 들어, N-1 = 3인 경우 1 3 2라는 배치에 4를 추가할 수 있는 위치는
_ 1 3 2
1 _ 3 2
1 3 _ 2
1 3 2 _
총 4곳입니다.

중요한 점은 가장 큰 동전 N을 추가하더라도 기존 동전들의 최종 앞면 여부는 변하지 않는다는 것입니다.
N은 다른 모든 동전보다 크므로 기존 동전을 뒤집을 수 없기 때문입니다.
따라서 기존 N-1개 동전의 정답은 N개의 삽입 위치마다 한 번씩 반복됩니다.

기존 동전들이 만들어 내는 앞면 개수의 총합은 N * dp[N-1]입니다.

3. 새롭게 추가한 N번 동전의 기여 계산

N번 동전은 자신보다 작은 동전이 왼쪽에 몇 개 있는지에 따라 뒤집히는 횟수가 정해집니다.
N번 동전을 맨 앞에 넣으면
왼쪽의 작은 동전 = 0개
뒤집히는 횟수 = 0번

한 칸 뒤에 넣으면
왼쪽의 작은 동전 = 1개
뒤집히는 횟수 = 1번

두 칸 뒤에 넣으면
왼쪽의 작은 동전 = 2개
뒤집히는 횟수 = 2번

이런 식으로 N번 동전이 뒤집히는 횟수는 0, 1, 2, ..., N-1이 됩니다.
이 중 홀수인 경우에만 N번 동전이 최종적으로 앞면을 보입니다.

0부터 N-1까지의 정수 중 홀수의 개수는 N / 2입니다.
여기서 /는 정수 나눗셈입니다.

기존 N-1개 동전의 배치는 (N-1)!가지이므로 N번 동전이 새롭게 만들어 내는 앞면 개수의 총합은 (N-1)! * (N / 2)입니다.

4. DP 점화식

dp[N] = N개 동전의 모든 순열에서 최종적으로 앞면을 보이는 동전 개수의 총합

기존 N-1개 동전들의 기여 N * dp[N-1]
새롭게 추가한 N번 동전의 기여 (N-1)! * (N / 2)
두 값을 더하면 dp[N] = N * dp[N-1] + (N-1)! * (N / 2)

초기값은 dp[1] = 0
동전이 하나뿐이면 뒤집을 수 있는 오른쪽 동전이 없기 때문입니다.

N <= 1000이므로 factorial[N]과 dp[N]을 미리 계산해 두면 각 테스트 케이스는 O(1)에 답을 구할 수 있습니다.
*/


/*
문제 풀이
*/

import java.io.*;

public class Solution {
    static final int MAX = 1000;
    static final long MOD = 1_000_000_007L;
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        StringBuilder sb = new StringBuilder();
        /*
        factorial[n]
        n!을 MOD로 나눈 나머지
        */
        long[] factorial = new long[MAX + 1];
        /*
        dp[n]
        1부터 n까지의 동전으로 만들 수 있는
        모든 순열에서 앞면 동전 개수의 총합
        */
        long[] dp = new long[MAX + 1];
        /*
        0! = 1
        */
        factorial[0] = 1;
        /*
        동전이 하나라면 뒤집히는 동전이 없으므로 정답은 0입니다.
        */
        dp[1] = 0;
        /*
        팩토리얼을 미리 계산합니다.
        factorial[i] = i * factorial[i-1]
        */
        for (int i = 1; i <= MAX; i++) {
            factorial[i] = factorial[i - 1] * i % MOD;
        }
        /*
        DP를 미리 계산합니다.
        dp[i] = i * dp[i-1] + (i-1)! * (i/2)

        첫 번째 항
        기존 i-1개 동전이 만드는 앞면 개수의 총합

        두 번째 항
        새롭게 추가한 i번 동전이 앞면을 보이는 경우의 총합
        */
        for (int i = 2; i <= MAX; i++) {
            long existing = i * dp[i - 1] % MOD;
            long added = factorial[i - 1] * (i / 2) % MOD;
            dp[i] = (existing + added) % MOD;
        }
        /*
        테스트 케이스 입력
        */
        int T = Integer.parseInt(br.readLine());
        for (int tc = 1; tc <= T; tc++) {
            int N = Integer.parseInt(br.readLine());
            /*
            미리 계산한 dp[N]을 출력합니다.
            */
            sb.append("#").append(tc).append(" ").append(dp[N]).append('\n');
        }
        System.out.print(sb);
    }
}


/*
시간복잡도

팩토리얼 전처리
O(MAX)

DP 전처리
O(MAX)

각 테스트 케이스의 정답 조회
O(1)

테스트 케이스가 T개라면 전체 시간복잡도는 O(MAX + T)
*/
