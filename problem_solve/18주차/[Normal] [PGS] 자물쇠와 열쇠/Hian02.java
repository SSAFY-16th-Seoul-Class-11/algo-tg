/*
문제 정의

M x M 크기의 열쇠와 N x N 크기의 자물쇠가 주어집니다.
0은 홈, 1은 돌기를 의미합니다.

열쇠는 다음 동작이 가능합니다.
1. 상하좌우 자유롭게 이동할 수 있습니다.
2. 90도 단위로 회전할 수 있습니다.

자물쇠가 열리려면 자물쇠 영역 안에서 다음 조건을 모두 만족해야 합니다.
1. 자물쇠의 홈(0)은 열쇠의 돌기(1)로 모두 채워져야 합니다.
2. 자물쇠의 돌기(1)와 열쇠의 돌기(1)가 겹치면 안 됩니다.
3. 열쇠에서 자물쇠 영역 밖으로 나간 부분은 아무 영향을 주지 않습니다.

열쇠를 적절하게 회전하고 이동해서 자물쇠를 열 수 있으면 true, 그렇지 않으면 false를 반환합니다.
*/


/*
접근 방법

열쇠를 0도, 90도, 180도, 270도로 총 4가지 방향으로 회전시키면서 모든 위치에 놓아봅니다.

열쇠의 왼쪽 위 위치를 (startRow, startCol)이라고 하겠습니다.
startRow, startCol은 자물쇠 밖에 위치할 수도 있습니다.
예를 들어 startRow가 -1이라면 열쇠의 첫 번째 행은 자물쇠 위쪽 영역에 있다는 의미입니다.

열쇠를 특정 위치에 놓았을 때 자물쇠의 모든 칸을 확인합니다.
자물쇠의 위치가 (r, c)일 때 그 위치와 겹치는 열쇠의 좌표는
keyRow = r - startRow
keyCol = c - startCol

keyRow와 keyCol이 열쇠 범위 안에 있다면 해당 열쇠 값을 사용하고, 범위 밖이라면 열쇠가 자물쇠와 겹치지 않는 위치이므로 0이라고 생각합니다.
자물쇠가 열리기 위한 조건은 모든 자물쇠 칸에서 lock[r][c] + keyValue == 1이어야 한다는 것입니다.

가능한 경우는 
lock = 0, key = 1 -> 홈을 돌기가 채움
lock = 1, key = 0 -> 기존 돌기 유지

불가능한 경우는
lock = 0, key = 0 -> 홈이 남아 있음
lock = 1, key = 1 -> 돌기끼리 충돌

열쇠의 위치는 자물쇠와 일부만 겹치는 경우뿐만 아니라 완전히 자물쇠 밖에 있는 경우까지 고려할 수 있도록 -M부터 N까지 확인합니다.
특히 자물쇠가 처음부터 모든 칸이 1이라면 열쇠를 자물쇠 밖으로 이동시키는 것만으로도 열 수 있으므로 이러한 경우도 자연스럽게 처리됩니다.
*/


/*
문제 풀이
*/

class Solution {
    /*
    현재 방향의 key를 모든 위치에 놓아보고 자물쇠를 열 수 있는지 확인합니다.
    */
    static boolean canOpen(int[][] key, int[][] lock) {
        int M = key.length;
        int N = lock.length;

        /*
        열쇠의 왼쪽 위 위치를 모든 가능한 위치로 이동시킵니다.
        -M이면 열쇠가 자물쇠의 위쪽/왼쪽으로 완전히 빠질 수도 있고 N이면 아래쪽/오른쪽으로 완전히 빠질 수도 있습니다.
        */
        for (int startRow = -M; startRow <= N; startRow++) {
            for (int startCol = -M; startCol <= N; startCol++) {
                boolean possible = true;
                /*
                자물쇠의 모든 칸을 확인합니다.
                */
                for (int r = 0; r < N && possible; r++) {
                    for (int c = 0; c < N; c++) {
                        /*
                        현재 자물쇠 위치와 겹치는 열쇠 좌표를 계산합니다.
                        */
                        int keyRow = r - startRow;
                        int keyCol = c - startCol;

                        /*
                        열쇠가 자물쇠와 겹치지 않는 경우에는 열쇠 값이 0이라고 생각합니다.
                        */
                        int keyValue = 0;

                        /*
                        열쇠 범위 안에 있다면 실제 열쇠 값을 사용합니다.
                        */
                        if (keyRow >= 0 && keyRow < M && keyCol >= 0 && keyCol < M) {
                            keyValue = key[keyRow][keyCol];
                        }
                        /*
                        자물쇠가 열리기 위해서는 각 칸의 합이 정확히 1이어야 합니다.

                        0 + 1 = 1 : 홈을 돌기가 채움
                        1 + 0 = 1 : 정상

                        0 + 0 = 0 : 홈이 남음
                        1 + 1 = 2 : 돌기 충돌
                        */
                        if (lock[r][c] + keyValue != 1) {
                            possible = false;
                            break;
                        }
                    }
                }

                /*
                모든 자물쇠 칸이 조건을 만족했다면 자물쇠를 열 수 있습니다.
                */
                if (possible) {
                    return true;
                }
            }
        }
        return false;
    }

    /*
    열쇠를 시계 방향으로 90도 회전합니다.

    기존 위치
    (r, c)

    회전 후 위치
    (c, M - 1 - r)
    */
    static int[][] rotate(int[][] key) {
        int M = key.length;
        int[][] rotated = new int[M][M];

        for (int r = 0; r < M; r++) {
            for (int c = 0; c < M; c++) {
                rotated[c][M - 1 - r] = key[r][c];
            }
        }
        return rotated;
    }

    public boolean solution(int[][] key, int[][] lock) {
        /*
        열쇠의 4가지 회전 상태를 모두 확인합니다.
        0회전 90도 180도 270도
        */
        for (int rotation = 0; rotation < 4; rotation++) {
            /*
            현재 방향의 열쇠를 모든 위치에 놓아봅니다.
            */
            if (canOpen(key, lock)) {
                return true;
            }
            /*
            다음 탐색을 위해 시계 방향으로 90도 회전합니다.
            */
            key = rotate(key);
        }
        /*
        모든 회전과 모든 위치를 확인했지만 열 수 없습니다.
        */
        return false;
    }
}

/*
시간복잡도
열쇠 크기를 M, 자물쇠 크기를 N이라고 하겠습니다.

열쇠는 총 4가지 방향으로 회전합니다.
각 방향에서 열쇠의 위치를 대략 (N + 2M)^2개 확인합니다.
각 위치마다 자물쇠의 N * N개 칸을 확인합니다.

따라서 전체 시간복잡도는 대략 O(4 * (N + M)^2 * N^2)입니다.

공간복잡도
90도 회전된 열쇠를 저장하기 위해 M x M 배열을 사용합니다.
따라서 공간복잡도는 O(M^2)입니다.


핵심 정리

1. 열쇠를 0도, 90도, 180도, 270도로 총 4가지 방향에서 확인합니다.
2. 각 방향마다 열쇠를 자물쇠 주변의 모든 위치로 이동시킵니다.
3. 자물쇠 밖으로 나간 열쇠 부분은 무시합니다.
4. 자물쇠의 모든 칸에서 lock 값 + 겹치는 key 값이 정확히 1이어야 합니다.
5. 0 + 1이면 자물쇠의 홈이 채워진 것이고, 1 + 0이면 기존 돌기가 유지된 것입니다.
6. 0 + 0이면 홈이 채워지지 않은 것이고, 1 + 1이면 돌기끼리 충돌한 것입니다.
7. 모든 자물쇠 칸의 합이 1이 되는 배치를 하나라도 찾으면 true를 반환합니다.
*/
